import { chromium, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const output = path.resolve('tests/ui/results'); await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || chromium.executablePath() });
const context = await browser.newContext({ viewport: { width: 1280, height: 980 } });
const page = await context.newPage();
const report = { checks: [], accessibility: [], errors: [] };
page.on('pageerror', error => report.errors.push(error.message));
const audit = async name => { const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze(); report.accessibility.push({ name, violations: result.violations.map(item => item.id) }); expect(result.violations).toEqual([]); };
try {
  await page.goto(`${process.env.HUB_TEST_URL || 'http://127.0.0.1:5173'}/tests/ui/discovery-harness.html`);
  await page.getByRole('navigation').getByRole('button', { name: 'Connexions', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Agents disponibles' })).toBeVisible();
  await page.getByRole('button', { name: 'Activer la détection', exact: true }).click();
  await expect(page.getByText('Installée · activée · 1.0.98')).toBeVisible();
  await expect(page.getByText('Non détectée', { exact: true })).toBeVisible();
  await audit('discovery-desktop');
  await page.screenshot({ path: path.join(output, 'discovery-desktop-synthetic.png'), fullPage: true });
  report.checks.push('known presence distinct from activity; optional permission enable');
  await page.getByRole('button', { name: 'Lancer', exact: true }).first().click();
  await page.getByLabel('Titre de la tâche', { exact: true }).fill('Essai de connexion — scénario synthétique');
  await page.getByLabel('Consigne', { exact: true }).fill('Return a synthetic test answer.');
  await expect(page.getByLabel('Conserver la réponse dans le reçu local')).not.toBeChecked();
  await page.getByLabel('Conserver la réponse dans le reçu local').check();
  await audit('launch-dialog');
  await page.getByRole('button', { name: 'Lancer la tâche', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Confirmation non reçue');
  await expect(page.locator('dialog textarea')).toBeDisabled();
  await page.getByRole('button', { name: 'Réessayer la même demande' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const requests = await page.evaluate(() => window.__hubDiscoveryTest.calls());
  expect(requests).toHaveLength(2); expect(requests[0]).toEqual(requests[1]); expect(requests[0].retainResult).toBe(true);
  report.checks.push('explicit result consent; uncertain retry keeps UUID and exact payload');
  await page.getByRole('button', { name: 'Arrêter', exact: true }).click();
  await expect(page.getByText('Tâche arrêtée.', { exact: true })).toBeVisible();
  report.checks.push('owned launch cancellation waits for confirmed response');
  await page.setViewportSize({ width: 360, height: 820 });
  await audit('discovery-360');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(output, 'discovery-360-synthetic.png'), fullPage: true });
  await page.getByRole('button', { name: 'Désactiver la détection', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Activer la détection', exact: true })).toBeVisible();
  report.checks.push('permission revocation clears discovery; narrow viewport has no page overflow');
  await page.locator('.language-select').selectOption('en');
  await expect(page.getByRole('heading', { name: 'Available agents' })).toBeVisible();
  report.checks.push('English discovery and launch copy');
  expect(report.errors).toEqual([]);
} finally { await writeFile(path.join(output, 'discovery-report.json'), JSON.stringify(report, null, 2)); await browser.close(); }
console.log(JSON.stringify(report));
