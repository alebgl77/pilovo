// Builds the static bilingual website from site/ into site-dist/ (or --out <dir>).
// Deterministic: no clock, no randomness, no network; the same inputs give the same bytes.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { copyFile, mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LANGS, PAGES, resolveSiteUrl } from '../site/src/config.mjs';
import en from '../site/src/content/en.mjs';
import fr from '../site/src/content/fr.mjs';
import { notices, llms, robots, sitemap } from '../site/src/files.mjs';
import { faqGraph, landingGraph } from '../site/src/jsonld.mjs';
import { rel, rewriteLink } from '../site/src/links.mjs';
import { loadMedia, variants } from '../site/src/media.mjs';
import { assertReadmeFaqInFaq, faqDoc, readme } from '../site/src/sources.mjs';
import { assertNoDash } from '../site/src/typography.mjs';
import { document, head } from '../site/src/pages/layout.mjs';
import { landingBody } from '../site/src/pages/landing.mjs';
import { faqBody, faqQuestions } from '../site/src/pages/faq.mjs';
import { NOT_FOUND, notFoundBody } from '../site/src/pages/not-found.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MARKER = '.site-build-output';
const CONTENT = { en, fr };
const TRACKED_TOP = ['site', 'docs', 'src', 'scripts', 'public', 'tests', 'companion', '.github', 'node_modules', '.git'];

function fail(message) {
  console.error(`build-site: ${message}`);
  process.exit(1);
}

function parseArgs(argv) {
  let out = path.join(repoRoot, 'site-dist');
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--out' && argv[i + 1]) out = path.resolve(argv[++i]);
    else if (argv[i].startsWith('--out=')) out = path.resolve(argv[i].slice(6));
    else fail(`unknown argument ${argv[i]}; use --out <dir>.`);
  }
  return { out };
}

// Refuses any output that could overwrite the repository or an unrelated folder.
async function prepareOut(out) {
  const resolved = path.resolve(out);
  if (resolved === path.parse(resolved).root) fail('refusing to write to the filesystem root.');
  const fromRepo = path.relative(repoRoot, resolved);
  if (fromRepo === '') fail('refusing to write to the repository root.');
  const toRepo = path.relative(resolved, repoRoot);
  if (!toRepo.startsWith('..') && !path.isAbsolute(toRepo)) fail('refusing to write to an ancestor of the repository.');
  const inside = !fromRepo.startsWith('..') && !path.isAbsolute(fromRepo);
  if (inside && TRACKED_TOP.includes(fromRepo.split(path.sep)[0])) fail(`refusing to write inside the tracked directory ${fromRepo.split(path.sep)[0]}/.`);
  if (existsSync(resolved)) {
    const entries = readdirSync(resolved);
    if (entries.length && !entries.includes(MARKER)) fail(`${out} exists, is not empty and is not a previous site build (no ${MARKER}).`);
    await rm(resolved, { recursive: true, force: true });
  }
  await mkdir(resolved, { recursive: true });
  await writeFile(path.join(resolved, MARKER), 'Generated by scripts/build-site.mjs; safe to delete.\n');
  return resolved;
}

// Light, deterministic compaction: drops comments and indentation, keeps every token as written.
function compact(text, kind) {
  const lines = (kind === 'css' ? text.replace(/\/\*[\s\S]*?\*\//g, '') : text).split('\n').map(line => line.trim());
  const kept = lines.filter(line => line && !(kind === 'js' && line.startsWith('//'))).join('\n');
  return (kind === 'css' ? kept.replace(/\s*([{};,])\s*/g, '$1').replace(/:\s+/g, ':') : kept) + '\n';
}

const sha8 = text => createHash('sha256').update(text).digest('hex').slice(0, 8);

function fontFaces() {
  const dir = path.join(repoRoot, 'node_modules/@fontsource-variable/montserrat');
  const css = readFileSync(path.join(dir, 'wght.css'), 'utf8');
  const wanted = ['montserrat-latin-ext-wght-normal.woff2', 'montserrat-latin-wght-normal.woff2'];
  const blocks = css.split(/(?=@font-face)/).filter(block => block.startsWith('@font-face'));
  const faces = wanted.map(file => {
    const block = blocks.find(b => b.includes(`/${file})`));
    if (!block) throw new Error(`Font block not found for ${file}`);
    if (!/font-display:\s*swap/.test(block) || !/font-weight:\s*100 900/.test(block) || !/unicode-range:/.test(block)) throw new Error(`Unexpected font block for ${file}`);
    return block.replace(/url\([^)]*\/(montserrat-[\w-]+\.woff2)\)/, 'url(fonts/$1)').replace(/\}[\s\S]*$/, '}').trim();
  });
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  return { css: faces.join('\n'), files: wanted.map(file => path.join(dir, 'files', file)), version: pkg.version, license: readFileSync(path.join(dir, 'LICENSE'), 'utf8') };
}

function lucideNotice() {
  const dir = path.join(repoRoot, 'node_modules/lucide-react');
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  return { version: pkg.version, license: readFileSync(path.join(dir, 'LICENSE'), 'utf8') };
}

async function walk(dir, base = dir) {
  const out = [];
  for (const entry of (await readdir(dir, { withFileTypes: true })).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await walk(full, base));
    else out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out;
}

const ids = htmlText => [...htmlText.matchAll(/\sid="([^"]+)"/g)].map(m => m[1].replace(/&amp;/g, '&'));

// Same-site URLs of a page must reach a written file, and their fragment an id of that file.
function checkLinks(pages, files, siteInfo) {
  const idsByFile = new Map(pages.map(page => [page.file, new Set(ids(page.html))]));
  const problems = [];
  for (const page of pages) {
    const base = new URL(page.url, siteInfo.site);
    const refs = [...page.html.matchAll(/\s(href|src|poster)="([^"]+)"/g)].map(m => m[2])
      .concat([...page.html.matchAll(/\ssrcset="([^"]+)"/g)].flatMap(m => m[1].split(',').map(part => part.trim().split(/\s+/)[0])));
    for (const ref of refs) {
      const target = new URL(ref.replace(/&amp;/g, '&'), base);
      if (target.origin !== siteInfo.origin || !target.pathname.startsWith(siteInfo.basePath)) continue;
      let file = decodeURIComponent(target.pathname.slice(siteInfo.basePath.length));
      if (file === '' || file.endsWith('/')) file += 'index.html';
      if (!files.has(file)) { problems.push(`${page.file}: ${ref} -> missing ${file}`); continue; }
      const hash = decodeURIComponent(target.hash.slice(1));
      if (hash && !/^t=/.test(hash) && !(idsByFile.get(file) || new Set()).has(hash)) problems.push(`${page.file}: ${ref} -> no #${hash} in ${file}`);
    }
  }
  if (problems.length) throw new Error(`Broken internal links:\n${problems.join('\n')}`);
}

async function main() {
  const { out: requested } = parseArgs(process.argv.slice(2));
  const siteInfo = resolveSiteUrl();
  const { site, basePath, origin } = siteInfo;
  const media = loadMedia(repoRoot);
  const font = fontFaces();
  const lucide = lucideNotice();

  const data = {};
  for (const lang of LANGS) {
    const c = CONTENT[lang];
    data[lang] = { readme: readme(repoRoot, c), faq: faqDoc(repoRoot, c) };
    assertReadmeFaqInFaq(data[lang].readme, data[lang].faq);
  }
  const faqIds = { en: data.en.faq.ids, fr: data.fr.faq.ids };

  const css = compact(`${font.css}\n${readFileSync(path.join(repoRoot, 'site/static/site.css'), 'utf8')}`, 'css');
  const js = compact(readFileSync(path.join(repoRoot, 'site/static/site.js'), 'utf8'), 'js');
  const assets = { css: `assets/site.${sha8(css)}.css`, js: `assets/site.${sha8(js)}.js` };

  const pages = [];
  const used = new Set();
  const makeCtx = (c, pageKey, fromDir) => ({
    c, site, basePath, origin, pageKey, fromDir, media, used, assets,
    readme: data[c.lang].readme, faq: data[c.lang].faq, faqPath: PAGES.faq[c.lang],
    url: target => (fromDir === null ? `${basePath}${target}` : rel(fromDir, target)),
    docLink: (href, sourceFile) => ({ href: rewriteLink(href, { sourceFile, repoRoot, faqIds, fromDir }).href }),
  });
  const alternatesFor = key => [['en', `${site}${PAGES[key].en}`], ['fr', `${site}${PAGES[key].fr}`], ['x-default', `${site}${PAGES[key].en}`]];

  for (const lang of LANGS) {
    const c = CONTENT[lang];
    const dir = PAGES.landing[lang];
    const ctx = makeCtx(c, 'landing', dir);
    const poster = variants(media.get(`tour-poster-${lang}`)).at(-1);
    const body = landingBody(ctx);
    const headHtml = head(ctx, {
      title: c.meta.landing.title, description: c.meta.landing.description, canonical: `${site}${dir}`, alternates: alternatesFor('landing'),
      jsonld: landingGraph({ site, content: c, media, title: ctx.c.meta.landing.title, description: c.meta.landing.description, poster }),
      preloadImage: poster.path,
    });
    pages.push({ file: `${dir}index.html`, url: dir, html: document(ctx, { headHtml, body }) });
  }
  for (const lang of LANGS) {
    const c = CONTENT[lang];
    const dir = PAGES.faq[lang];
    const ctx = makeCtx(c, 'faq', dir);
    const body = faqBody(ctx);
    const questions = faqQuestions(c, data[lang].faq);
    const headHtml = head(ctx, {
      title: c.meta.faq.title, description: c.meta.faq.description, canonical: `${site}${dir}`, alternates: alternatesFor('faq'),
      jsonld: faqGraph({ site, content: c, media, title: c.meta.faq.title, description: c.meta.faq.description, questions }),
    });
    pages.push({ file: `${dir}index.html`, url: dir, html: document(ctx, { headHtml, body }) });
  }
  {
    const ctx = makeCtx(en, '404', null);
    const body = notFoundBody(ctx);
    const headHtml = head(ctx, { title: NOT_FOUND.title, description: NOT_FOUND.description, robots: 'noindex' });
    pages.push({ file: '404.html', url: `${basePath}404.html`, html: document(ctx, { headHtml, body }) });
  }

  // JSON-LD titles and descriptions go through the same typography as the head.
  for (const page of pages) {
    assertNoDash(page.file, page.html);
    const seenIds = new Set();
    for (const id of ids(page.html)) {
      if (seenIds.has(id)) throw new Error(`Duplicate id "${id}" in ${page.file}`);
      seenIds.add(id);
    }
  }
  const textFiles = {
    'sitemap.xml': sitemap(site),
    'robots.txt': robots(site),
    'llms.txt': llms(site),
  };
  for (const [name, text] of Object.entries(textFiles)) assertNoDash(name, text);
  textFiles['third-party-notices.txt'] = notices({ fontVersion: font.version, fontLicense: font.license, lucideVersion: lucide.version, lucideLicense: lucide.license });
  // .nojekyll only matters for branch-based Pages: upload-pages-artifact leaves dotfiles out of the
  // Actions deployment, where Jekyll does not run anyway. Kept so a copy of site-dist/ also works on a branch.
  textFiles['.nojekyll'] = '';

  const out = await prepareOut(requested);
  const written = new Set();
  const write = async (relative, content) => {
    const target = path.join(out, relative);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
    written.add(relative);
  };
  const copy = async (from, relative) => {
    const target = path.join(out, relative);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(from, target);
    written.add(relative);
  };
  for (const page of pages) await write(page.file, page.html);
  for (const [name, text] of Object.entries(textFiles)) await write(name, text);
  await write(assets.css, css);
  await write(assets.js, js);
  for (const file of font.files) await copy(file, `assets/fonts/${path.basename(file)}`);
  for (const [from, to] of [['docs/media/pilovo-logo.svg', 'pilovo-logo.svg'], ['docs/media/pilovo-logo-light.svg', 'pilovo-logo-light.svg'], ['docs/media/pilovo-icon.svg', 'favicon.svg'], ['docs/media/pilovo-social-preview.png', 'pilovo-social-preview.png']]) {
    await copy(path.join(repoRoot, from), `assets/brand/${to}`);
  }
  for (const file of await walk(path.join(repoRoot, 'site/assets/brand'))) await copy(path.join(repoRoot, 'site/assets/brand', file), `assets/brand/${file}`);
  for (const file of await walk(path.join(repoRoot, 'site/assets/media'))) {
    if (file === 'media.json') continue;
    await copy(path.join(repoRoot, 'site/assets/media', file), `assets/media/${file}`);
  }
  for (const file of used) if (!written.has(file)) throw new Error(`Referenced media not written: ${file}`);
  checkLinks(pages, written, siteInfo);

  let bytes = 0;
  for (const file of written) bytes += (await stat(path.join(out, file))).size;
  console.log(JSON.stringify({ out: path.relative(repoRoot, out) || '.', site, pages: pages.map(p => p.file), files: written.size, bytes }));
}

main().catch(error => fail(error.stack || String(error)));
